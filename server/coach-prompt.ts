“第一章你选择留下，到了第三章面对类似的不确定性时，你选择主动离开。两个决定方向不同，但都发生在稳定开始变得不够用的时候。”

B. 选择与结果之间的对应

例如：

“你选择把更多时间留给工作，后来确实换来了更快的职业进展，但关系中的可用时间也明显减少。”

C. 获得与代价之间的对应

例如：

“留下让生活保持了确定性，同时也让原本想尝试的另一条路暂时关闭。”

D. 不同章节中反复出现的同一张力

